# Helper function to create subplots
def create_subplots(fig, gridspec, positions):
    """
         Helper function to create subplots to a figure at specified GridSpec positions.
        Parameters
        ----------
        fig : matplotlib.figure.Figure
            Figure to which the subplots will be added.
        gridspec : matplotlib.gridspec.GridSpec
            GridSpec defining the layout and positions available for the
            subplots.
        positions : sequence of int
            Indices of the GridSpec positions at which to create the subplots.

        Returns
        -------
        axes : list of matplotlib.axes.Axes
            List of axes corresponding to the requested GridSpec positions.
        """

    axes = [plt.Subplot(fig, gridspec[pos]) for pos in positions]
    for ax in axes:
        fig.add_subplot(ax)
    return axes
